/**
 * Returns peer comparison data for a given symbol.
 * Finds which industry peer group the symbol belongs to,
 * assigns `isCurrentStock: true` to the selected stock,
 * and returns the remaining peer group companies.
 */
export function getMockPeerComparison(symbol: string, exchange: string = 'NSE'): PeerComparisonResponse {
    const symUpper = symbol.toUpperCase()

    // 1. Search for matching peer group containing this symbol
    let matchedGroup: PeerGroupDefinition | undefined
    for (const group of Object.values(PEER_GROUPS)) {
        if (group.symbols.includes(symUpper)) {
            matchedGroup = group
            break
        }
    }

    // 2. Fallback to IT Services if not found in predefined list
    if (!matchedGroup) {
        matchedGroup = PEER_GROUPS['Information Technology']
    }

    // 3. Find current stock metrics in the group, or construct a realistic item
    let currentStock = matchedGroup.companies.find(c => c.symbol === symUpper)
    if (!currentStock) {
        currentStock = {
            symbol: symUpper,
            name: `${symUpper} Ltd.`,
            exchange: (exchange.toUpperCase() as Exchange) || 'NSE',
            cmp: 1250.00,
            marketCapCr: 350000.00,
            pe: 22.50,
            pb: 4.80,
            bookValue: 260.40,
            divYieldPct: 1.85,
            netProfitCr: 4500.00,
            profitGrowthPct: 12.40,
            roePct: 20.50,
            rocePct: 24.80,
            opmPct: 19.50,
            npmPct: 13.80,
            salesCr: 32600.00,
            salesGrowthPct: 11.80,
            annualRevenueGrowthPct: 12.10,
            annualProfitGrowthPct: 14.50,
            epsGrowthPct: 13.90,
            debtToEquity: 0.12,
            currentRatio: 1.85,
            interestCoverage: 32.40,
            promoterHoldingPct: 54.20,
            promoterPledgingPct: 0.00,
        }
    }

    // 4. Mark isCurrentStock flag
    const currentStockWithFlag: PeerCompanyMetricData = {
        ...currentStock,
        isCurrentStock: true,
    }

    // 5. Remaining peers (excluding current stock)
    const availablePeers = matchedGroup.companies
        .filter(c => c.symbol !== symUpper)
        .map(c => ({ ...c, isCurrentStock: false }))

    // 6. Up to 4 initial peers shown alongside current stock (making up to 5 default rows)
    const initialPeerSymbols = availablePeers.slice(0, 4).map(c => c.symbol)

    return {
        sector: matchedGroup.sector,
        industry: matchedGroup.industry,
        currentStock: currentStockWithFlag,
        availablePeers,
        initialPeerSymbols,
    }
}
