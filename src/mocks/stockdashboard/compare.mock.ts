export function getMockCompareData(symbol: string): StockComparisonData {
    const upper = symbol.toUpperCase()
    if (MOCK_COMPARE_STOCKS[upper]) return MOCK_COMPARE_STOCKS[upper]

    const inst = MOCK_INSTRUMENTS.find(i => i.symbol === upper) ?? MOCK_INSTRUMENTS[0]
    return {
        symbol: inst.symbol,
        name: inst.name,
        exchange: inst.exchange,
        sector: inst.sector,
        currentPrice: inst.quote.currentPrice,
        percentChange: inst.quote.percentChange,
        marketCapCr: inst.screenerMetrics.marketCapCr,
        peRatio: inst.screenerMetrics.peRatio,
        pbRatio: inst.screenerMetrics.pbRatio,
        roe: inst.screenerMetrics.roe,
        roce: inst.screenerMetrics.roce,
        evEbitda: 16.5,
        debtToEquity: inst.screenerMetrics.debtToEquity,
        operatingMargin: 18.5,
        revenueGrowth: inst.screenerMetrics.revenueGrowthYoY,
        profitGrowth: inst.screenerMetrics.profitGrowthYoY,
        dividendYield: 1.2,
        rsi14: inst.screenerMetrics.rsi14,
        beta: 1.0,
        high52w: inst.quote.week52High,
        low52w: inst.quote.week52Low,
    }
}
